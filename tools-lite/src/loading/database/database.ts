import { SceneContext } from "@babylonjs/lite";

import { waitUntil } from "../../tools/tools";
import { getSceneData } from "../../tools/scene";
import { addFileLoaderOverride, ILoadFileProgressEvent, loadFileFromNetwork } from "../../tools/request";

import { getFromIndexDB, openIndexDB, putInIndexDB } from "./indexdb";

let offlineDatabaseName: string | null = null;

/**
 * Setups offline support for the scene loading using IndexedDB as offline storage.
 * This allows scenes and assets to be loaded from the local database when offline.
 * Each scene loaded using `loadScene` opens the database when the manifest of the scene is available (`.babylon.manifest`
 * file generated by the editor): the files of the scene (scene file, geometries, textures, sounds, etc.) are then loaded
 * from the database when their version matches the version of the manifest, and from the network otherwise.
 * @param name defines the name of the database to setup
 */
export function setupOfflineProvider(name: string) {
	offlineDatabaseName = name;
}

/**
 * @internal
 * Opens the offline database (see `setupOfflineProvider`) for the given scene file and loads the files requested by
 * the tools from the database while the scene exists.
 * @param scene defines the reference to the scene being loaded.
 * @param urlToScene defines the url of the scene file being loaded.
 */
export async function _attachOfflineDatabase(scene: SceneContext, urlToScene: string): Promise<void> {
	if (!offlineDatabaseName) {
		return;
	}

	const database = await createAndOpenDatabase(offlineDatabaseName, urlToScene);
	if (!database) {
		return;
	}

	const removeOverride = addFileLoaderOverride((url, responseType, progressCallback) => {
		if (responseType === "blob") {
			return database.enableTexturesOffline ? database.loadFileAsync(url, "blob") : null;
		}

		return database.enableSceneOffline ? database.loadFileAsync(url, responseType, progressCallback) : null;
	});

	getSceneData(scene).onDisposeObservable.addOnce(() => {
		removeOverride();
		database.close();
	});
}

/**
 * Creates a database for offline support and opens it.
 * If the database already exists in indexDB, it will be opened and returned. Otherwise, a new database will be created and opened.
 * @param name defines the name of the database to create (if doesn't exists) and open
 * @param urlToScene defines the Url of the scene to load.
 */
export async function createAndOpenDatabase(name: string, urlToScene: string) {
	const database = await new Promise<Database | null>((resolve) => {
		const databaseInstance = new Database(name, urlToScene, (checked) => resolve(checked ? databaseInstance : null), false);
	});

	await database?.open();

	return database;
}

interface _IVersionObjectStore {
	url: string;
	version: number;
}

export interface _IFilesObjectStore {
	url: string;
	data: string | ArrayBuffer | Blob;
}

export class Database {
	/**
	 * Gets a boolean indicating if scene must be saved in the database
	 */
	public enableSceneOffline: boolean = true;
	/**
	 * Gets a boolean indicating if textures must be saved in the database
	 */
	public enableTexturesOffline: boolean = true;

	/**
	 * Defines the name of the database.
	 */
	public readonly name: string;

	private _database: IDBDatabase | null = null;
	private _manifestVersion: number | null = null;

	private _loadFilePromises: Map<string, Promise<any>> = new Map();

	public constructor(name: string, urlToScene: string, callbackManifestChecked: (checked: boolean) => any, disableManifestCheck: boolean) {
		this.name = name;

		if (disableManifestCheck) {
			callbackManifestChecked(false);
		} else {
			this._checkManifest(urlToScene, callbackManifestChecked);
		}
	}

	private async _checkManifest(urlToScene: string, callbackManifestChecked: (checked: boolean) => any): Promise<void> {
		try {
			// The manifest is always loaded from the network: it defines the version of the files stored in the database.
			const manifest = JSON.parse(await loadFileFromNetwork(`${urlToScene}.manifest?${Date.now()}`, "text"));

			this._manifestVersion = manifest.version;
			callbackManifestChecked(true);
		} catch (e) {
			this.enableSceneOffline = false;
			this.enableTexturesOffline = false;

			callbackManifestChecked(false);
		}
	}

	/**
	 * Open the offline support and make it available
	 * @param successCallback defines the callback to call on success
	 * @param errorCallback defines the callback to call on error
	 */
	public async open(successCallback?: () => void, errorCallback?: () => void): Promise<void> {
		try {
			this._database = await openIndexDB(this.name, (database) => {
				database.createObjectStore("files", { keyPath: "url" });
				database.createObjectStore("images", { keyPath: "url" });
				database.createObjectStore("versions", { keyPath: "url" });
			});

			successCallback?.();
		} catch (e) {
			errorCallback?.();
		}
	}

	public close(): void {
		this._database?.close();
		this._database = null;

		this._loadFilePromises.clear();
	}

	/**
	 * Loads an image from the offline support
	 * @param url defines the url to load from
	 * @param image defines the target DOM image
	 */
	public async loadImage(url: string, image: HTMLImageElement): Promise<void> {
		if (!this._database) {
			image.src = url;
			return;
		}

		const data = await this.loadFileAsync(url, "blob");
		image.src = data ? URL.createObjectURL(data) : url;
	}

	public async saveImage(url: string): Promise<void> {
		if (!this._database) {
			throw new Error("Database is not available");
		}

		const data = await loadFileFromNetwork(url, "blob");

		await Promise.all([
			putInIndexDB<_IFilesObjectStore>(this._database, "images", { url, data }),
			putInIndexDB<_IVersionObjectStore>(this._database, "versions", {
				url,
				version: this._manifestVersion!,
			}),
		]);
	}

	/**
	 * Checks wehter or not the file located at the given URL is matching the current manifest version in the database.
	 * @param url defines the URL to check the version for
	 */
	public async isFileMatchingVersion(url: string): Promise<boolean> {
		const version = await this._getFileVersionForUrl(url);
		return version === this._manifestVersion;
	}

	/**
	 * Loads a file from offline support
	 * @param url defines the URL to load from
	 * @param sceneLoaded defines a callback to call on success
	 * @param progressCallBack defines a callback to call when progress changed
	 * @param errorCallback defines a callback to call on error
	 * @param useArrayBuffer defines a boolean to use array buffer instead of text string
	 */
	public async loadFile(
		url: string,
		sceneLoaded: (data: any) => void,
		progressCallBack?: (data: ILoadFileProgressEvent) => void,
		errorCallback?: () => void,
		useArrayBuffer?: boolean
	): Promise<void> {
		if (!this._database) {
			return errorCallback?.();
		}

		try {
			const data = await this.loadFileAsync(url, useArrayBuffer ? "arraybuffer" : "text", progressCallBack);
			if (data !== null) {
				sceneLoaded(data);
			} else {
				errorCallback?.();
			}
		} catch (e) {
			errorCallback?.();
		}
	}

	/**
	 * Loads the file located at the given url: from the database when its version matches the version of the manifest
	 * of the scene, from the network otherwise (the file is then saved in the database).
	 * @param url defines the URL to load from.
	 * @param responseType defines the type of the expected content. The "blob" type is used for the images.
	 * @param progressCallBack defines a callback to call when progress changed.
	 * @returns a promise resolved with the content of the file, or null if the database is not available.
	 */
	public async loadFileAsync(url: string, responseType: "text" | "arraybuffer" | "blob", progressCallBack?: (data: ILoadFileProgressEvent) => void): Promise<any> {
		if (!this._database) {
			return null;
		}

		await waitUntil(() => this._manifestVersion !== null);

		const key = `${responseType}:${url}`;

		let loadingPromise = this._loadFilePromises.get(key);
		if (!loadingPromise) {
			loadingPromise = this._loadFile(url, responseType, progressCallBack);
			this._loadFilePromises.set(key, loadingPromise);
		}

		return loadingPromise;
	}

	private async _loadFile(url: string, responseType: "text" | "arraybuffer" | "blob", progressCallBack?: (data: ILoadFileProgressEvent) => void): Promise<any> {
		const store = responseType === "blob" ? "images" : "files";
		const version = await this._getFileVersionForUrl(url);

		if (version === this._manifestVersion) {
			const data = (await getFromIndexDB<_IFilesObjectStore>(this._database!, store, url))?.data ?? null;
			if (data !== null) {
				return data;
			}

			// The binary files preloaded in the database (ie. KTX2 textures) are loaded as blobs by the textures loaders.
			if (responseType === "blob") {
				const binaryData = (await getFromIndexDB<_IFilesObjectStore>(this._database!, "files", url))?.data ?? null;
				if (binaryData instanceof ArrayBuffer) {
					return new Blob([binaryData]);
				}
			}
		}

		const data = await loadFileFromNetwork(url, responseType, progressCallBack);

		await Promise.all([
			putInIndexDB<_IFilesObjectStore>(this._database!, store, { url, data }),
			putInIndexDB<_IVersionObjectStore>(this._database!, "versions", {
				url,
				version: this._manifestVersion!,
			}),
		]);

		return data;
	}

	public async saveFile(url: string, useArrayBuffer: boolean, progress?: (data: ILoadFileProgressEvent) => void): Promise<void> {
		if (!this._database) {
			throw new Error("Database is not available");
		}

		const data = await loadFileFromNetwork(url, useArrayBuffer ? "arraybuffer" : "text", progress);

		await Promise.all([
			putInIndexDB<_IFilesObjectStore>(this._database, "files", { url, data }),
			putInIndexDB<_IVersionObjectStore>(this._database, "versions", {
				url,
				version: this._manifestVersion!,
			}),
		]);
	}

	private async _getFileVersionForUrl(url: string): Promise<number | null> {
		const data = await getFromIndexDB<_IVersionObjectStore>(this._database!, "versions", url);
		return data?.version ?? null;
	}
}
